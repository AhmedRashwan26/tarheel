#!/bin/bash
# ==============================================================================
# منصة تـرحـيـل (Tarheel) - سكربت الصيانة والتنظيف الذاتي التلقائي لسيرفر Hetzner
# ==============================================================================
# يقوم هذا السكربت بحماية مساحة السيرفر من الامتلاء تلقائياً:
# 1. تفريغ كاش دوكر والحاويات المؤقتة.
# 2. تقليص وتدوير سجلات النظام (Journal Logs) الأقدم من 7 أيام.
# 3. تفريغ حزم التثبيت المؤقتة (apt cache).
# 4. منع تراكم سجلات Docker عبر إعداد logrotate.
# ==============================================================================

set -e

echo "🚀 [Tarheel Server Auto-Maintenance] بدء الصيانة الدورية للسيرفر..."
DATE=$(date '+%Y-%m-%d %H:%M:%S')
echo "📅 التوقيت الحالي: $DATE"

# 1. تفريغ كاش النظام وحزم التحديثات
echo "🧹 [1/4] تنظيف حزم apt المؤقتة..."
sudo apt-get clean -y
sudo apt-get autoremove -y --purge

# 2. تنظيف سجلات نظام لينكس الأقدم من 7 أيام
echo "📜 [2/4] تفريغ سجلات journalctl القديمة لتوفير المساحة..."
sudo journalctl --vacuum-time=7d
sudo journalctl --vacuum-size=200M

# 3. تنظيف بيئة Docker والحاويات المهملة
if command -v docker &> /dev/null; then
    echo "🐳 [3/4] تفريغ كاش Docker والصور غير المستخدمة..."
    sudo docker system prune -f --volumes || true
fi

# 4. إعداد تدوير سجلات Docker التلقائي لمنع تضخمها
echo "⚙️ [4/4] التأكد من إعدادات تدوير السجلات Logrotate..."
if [ ! -f /etc/docker/daemon.json ]; then
    echo "📝 إنشاء إعدادات تحجيم سجلات دوكر بحد أقصى 50MB..."
    sudo mkdir -p /etc/docker
    sudo tee /etc/docker/daemon.json > /dev/null <<EOF
{
  "log-driver": "json-file",
  "log-opts": {
    "max-size": "50m",
    "max-file": "3"
  }
}
EOF
    echo "✅ تم ضبط الحد الأقصى لسجلات دوكر بـ 50MB."
fi

# عرض النتيجة النهائية للمساحة
echo "========================================================="
echo "🎉 اكتملت عملية الصيانة الذاتية بنجاح!"
echo "📊 حالة مساحة القرص الصلب الحالية:"
df -h /
echo "📊 حالة الذاكرة العشوائية الحالية:"
free -m
echo "========================================================="
